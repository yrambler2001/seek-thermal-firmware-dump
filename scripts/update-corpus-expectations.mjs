/**
 * Regenerate `packages/core/test/corpus/expectations.json` from a local dump corpus.
 *
 * The corpus itself is real camera flash and is deliberately NOT in this
 * repository. What IS committed is this file's output: a small table of facts,
 * keyed by each dump's sha256, that `packages/core/test/corpus.test.ts` then
 * asserts the core still reproduces. Committing the facts rather than the dumps
 * is what makes a real-hardware regression test survive in a public repo.
 *
 * Keying on the dump's own sha256 — not its filename — is deliberate. Filenames
 * in a dump collection are ad hoc, get renamed, and carry spaces and unicode;
 * the content hash is the only stable identity a dump has. It also means a
 * silently corrupted dump shows up as an unknown dump rather than as a
 * mysterious mismatch.
 *
 * Usage:
 *   npm run build                                  # the script imports from dist
 *   node scripts/update-corpus-expectations.mjs [dumpDir]
 *
 * `dumpDir` defaults to $SEEK_DUMPS_DIR, then to ../SEEK_DUMPS next to the repo,
 * matching `scripts/verify-against-legacy.mjs`.
 *
 * Adding a dump to the corpus is an EXPANSION, never a correction: re-running
 * this script over a wider corpus should only ever add entries. If it changes an
 * existing entry, the core's behaviour changed on a dump it used to handle —
 * read the diff before committing it.
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { decryptDump, silentReporter } from '../packages/core/dist/index.js';

const FLASH_SIZE = 4 * 1024 * 1024;
const repoRoot = path.resolve(import.meta.dirname, '..');
const outPath = path.join(repoRoot, 'packages', 'core', 'test', 'corpus', 'expectations.json');

const sha = (b) => createHash('sha256').update(b).digest('hex');
const hex = (n) => `0x${(n >>> 0).toString(16).toUpperCase().padStart(8, '0')}`;

const dumpDir =
  process.argv[2] ?? process.env.SEEK_DUMPS_DIR ?? path.resolve(repoRoot, '..', 'SEEK_DUMPS');

if (!existsSync(dumpDir)) {
  console.error(`no dump directory at ${dumpDir}`);
  process.exit(1);
}

/** Every 4 MiB *.bin under `dir`, recursively. */
function findDumps(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...findDumps(full));
    } else if (entry.isFile() && /\.bin$/i.test(entry.name) && statSync(full).size === FLASH_SIZE) {
      out.push(full);
    }
  }
  return out;
}

const previous = existsSync(outPath) ? JSON.parse(readFileSync(outPath, 'utf8')) : { dumps: {} };
const dumps = {};
let changed = 0;

for (const file of findDumps(dumpDir).sort()) {
  const bytes = new Uint8Array(readFileSync(file));
  const digest = sha(bytes);
  const stem = path.basename(file).replace(/\.bin$/i, '');

  const result = await decryptDump(bytes, stem, {}, silentReporter);

  const entry = {
    /* A human label only. The sha256 key is the identity; this is so a failure
     * message can name something a person recognises. Renaming a dump file is
     * not a behaviour change, so this field is excluded from the assertions. */
    label: path.relative(dumpDir, file),
    profile: result.detection?.best.profile.id ?? null,
    ambiguous: result.detection?.ambiguous ?? null,
    slots: result.slots.map((s) => ({
      flash: hex(s.flash),
      length: s.length,
      acceptanceSum: hex(s.recovered.checksum),
      whiteningK: hex(s.whitening.whiteningK),
      sp: hex(s.sp),
      entry: hex(s.entry),
      confidence: s.recovered.confidence,
      whiteningEvidence: s.whitening.evidence,
      duplicateOf: s.duplicateOf === null ? null : hex(s.duplicateOf),
      plainSha256: s.plainSha256,
    })),
  };

  const before = previous.dumps?.[digest];
  if (
    before &&
    JSON.stringify({ ...before, label: '' }) !== JSON.stringify({ ...entry, label: '' })
  ) {
    console.warn(`CHANGED  ${entry.label}  (${digest.slice(0, 12)}…)`);
    changed += 1;
  } else if (!before) {
    console.log(`new      ${entry.label}  (${digest.slice(0, 12)}…)`);
  }
  dumps[digest] = entry;
}

const payload = {
  $comment:
    'Generated by scripts/update-corpus-expectations.mjs. Keys are the sha256 of a 4 MiB ' +
    'flash dump; the dumps themselves are not in this repository. See packages/core/test/corpus.test.ts. ' +
    'There is deliberately no timestamp in here: a regenerated file should diff only where behaviour changed.',
  dumpCount: Object.keys(dumps).length,
  dumps,
};

writeFileSync(outPath, `${JSON.stringify(payload, null, 2)}\n`);
console.log(
  `\nwrote ${String(payload.dumpCount)} dump(s) to ${path.relative(repoRoot, outPath)}` +
    (changed ? `  — ${String(changed)} CHANGED, read the diff` : ''),
);
